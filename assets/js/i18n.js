let current = DEFAULT_LOCALE;

export function setLocale(locale) {
  current = LOCALES.includes(locale) ? locale : DEFAULT_LOCALE;
  document.documentElement.lang = current;
}

export function getLocale() {
  return current;
}

/**
 * Traduit une clé. `params` remplace les %jetons%.
 * `params.count` sélectionne la forme plurielle (« un|plusieurs »).
 */
export function t(key, params = {}) {
  let msg = MESSAGES[current]?.[key];
  if (msg === undefined) msg = MESSAGES[DEFAULT_LOCALE][key];
  if (msg === undefined) return key;
  if (msg.includes("|")) {
    const forms = msg.split("|");
    const n = Number(params.count ?? 1);
    msg = n > 1 ? forms[1] : forms[0];
  }
  return msg.replace(/%(\w+)%/g, (m, k) => (params[k] !== undefined ? params[k] : m));
}
